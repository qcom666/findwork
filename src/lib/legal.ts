const rub = (n: number) => `${n.toLocaleString("ru-RU")} ₽`;
const credits = (n: number) => `${n} ${plural(n, "кредит", "кредита", "кредитов")}`;
const site = () => process.env.APP_URL?.replace(/\/$/, "") || "https://findwork-rouge.vercel.app";

/** Строки реквизитов, общие для всех документов. */
function details(): string[] {
  const s = seller;
  return [
    `Исполнитель (оператор): ${s.name()}, ${s.status()}`,
    `ИНН: ${s.inn()}`,
    ...(s.ogrn() ? [`ОГРН / ОГРНИП: ${s.ogrn()}`] : []),
    ...(s.address() ? [`Адрес: ${s.address()}`] : []),
    ...(s.phone() ? [`Телефон: ${s.phone()}`] : []),
    `Электронная почта: ${s.email()}`,
    ...(s.telegram() ? [`Telegram: ${s.telegram()}`] : []),
    `Сайт: ${site()}`,
  ];
}

