/** Включена ли генерация питчей языковой моделью. Без ключа сервис честно работает на шаблонах и не пишет на сайте про ИИ. */
export const aiPitches = (): boolean => !!process.env.ANTHROPIC_API_KEY?.trim();

/** Название питча в тарифах и на лендинге: говорим про Claude только когда он правда подключён. */
export const pitchFeature = (ai = aiPitches()): string => (ai ? "Питч от Claude под каждое заведение" : "Готовый питч под каждое заведение");
